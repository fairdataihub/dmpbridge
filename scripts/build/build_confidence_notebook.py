        "EXTRACTOR, SAMPLES = 'pdfplumber', range(1, 11)",
        "",
        "pd.set_option('display.max_colwidth', 62)",
        "INK, MUTED, SURFACE, GRID = '#111111', '#52514e', '#fcfcfb', '#e6e6e2'",
