"""Build notebooks/analysis-gemma4-e4b-sample-by-sample.ipynb.

A plain-language walkthrough of gemma4:e4b's FINAL output (stage 4 — the
actual finished document the pipeline produces, after the automatic fix-up
rules run) against the answer key it's graded against (Path B only).

Each sample renders as the real document — title, then each section's
heading, question and answer, in reading order. Items that match the answer
key exactly show with nothing extra next to them. Items that don't match get
a light highlight and a short plain-English note explaining why, in place of
any icon, tag, or code-like syntax — built for a non-technical reader to
scan a sample and understand every flag without translation.

    python scripts/build/build_gemma_sample_walkthrough.py
"""
