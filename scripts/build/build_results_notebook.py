        "COLS = list(LABELS) + ['(not labeled)']",
        "KEYS = list(LABELS) + ['__missed__']",
        "",
        "",
        "def build_pct(conf):",
        "    \"\"\"Row-percentage matrix: cell (i, j) = share of true class i predicted",
